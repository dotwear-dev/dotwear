// 1 つのグリッドから SVG 文字列を作る。
// Web 用の出力と pixel-roundtrip テストの両方がこの関数を使うので、テストは実際の出力と同じ形を検証できる。
import { gridToRects, rectsToPath, type CellColor } from "../paths/rects.js";

export const GENERATED_HEADER = "Generated by dotwear generator. DO NOT EDIT.";

/** 色の文字 → SVG の fill の値 */
export type FillResolver = (color: CellColor) => string;

export interface SvgLayer {
  color: CellColor;
  d: string;
}

/** グリッドを色ごとのパスにする（色ごとに 1 本） */
export function gridToLayers(grid: readonly string[]): SvgLayer[] {
  return [...gridToRects(grid)].map(([color, rects]) => ({ color, d: rectsToPath(rects) }));
}

/** CSS 変数のフォールバックに使う色を受け取り、Web 用の fill を返す */
export function webFillResolver(defaults: Partial<Record<CellColor, string>>): FillResolver {
  return (color) => {
    if (color === "#") return "currentColor";
    const fallback = defaults[color];
    // <img> で読み込んだ SVG には CSS 変数が届かないので、default テーマの色をフォールバックにする
    return fallback ? `var(--dw-palette-${color}, ${fallback})` : `var(--dw-palette-${color})`;
  };
}

export interface RenderSvgOptions {
  fill: FillResolver;
  /** 先頭に「生成物」コメントを入れるか（配布する .svg では入れる） */
  header?: boolean;
}

export function renderSvg(grid: readonly string[], options: RenderSvgOptions): string {
  const size = grid.length;
  const paths = gridToLayers(grid)
    .map((l) => `<path fill="${options.fill(l.color)}" d="${l.d}"/>`)
    .join("");
  // crispEdges：境界のアンチエイリアスを止める。座標が整数なので、整数倍の表示ではにじまない
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}" shape-rendering="crispEdges">` +
    paths +
    `</svg>`;
  return options.header ? `<!-- ${GENERATED_HEADER} -->\n${svg}\n` : svg;
}
