// フォントのコピー（ADR-026）。フォントは必ずライセンス文と一緒に配る
import { mkdtemp, readdir, readFile, rm } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { afterAll, describe, expect, it } from "vitest";
import { androidFontResourceName, emitAndroidFonts, emitFonts, emitWebFonts } from "../src/emit/fonts.js";

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const dirs: string[] = [];
afterAll(() => Promise.all(dirs.map((d) => rm(d, { recursive: true, force: true }))));

describe("emitFonts", () => {
  it("フォントのファイルと OFL のライセンス文を、元と同じ中身でコピーする", async () => {
    const outDir = await mkdtemp(path.join(os.tmpdir(), "dw-fonts-"));
    dirs.push(outDir);
    expect(await emitFonts({ root: REPO_ROOT, outDir })).toEqual(["DotGothic16-Regular.ttf"]);
    expect((await readdir(outDir)).sort()).toEqual(["DotGothic16-OFL.txt", "DotGothic16-Regular.ttf"]);
    const [copied, source] = await Promise.all([
      readFile(path.join(outDir, "DotGothic16-Regular.ttf")),
      readFile(path.join(REPO_ROOT, "fonts", "DotGothic16", "DotGothic16-Regular.ttf")),
    ]);
    expect(copied.equals(source)).toBe(true);
    expect(await readFile(path.join(outDir, "DotGothic16-OFL.txt"), "utf8")).toContain("SIL Open Font License");
  });
});

describe("emitWebFonts", () => {
  it("fonts/ にフォントとライセンス文を置き、fonts.css から相対パスで読む", async () => {
    const outDir = await mkdtemp(path.join(os.tmpdir(), "dw-web-fonts-"));
    dirs.push(outDir);
    await emitWebFonts({ root: REPO_ROOT, outDir });
    expect((await readdir(path.join(outDir, "fonts"))).sort()).toEqual(["DotGothic16-OFL.txt", "DotGothic16-Regular.ttf"]);
    const css = await readFile(path.join(outDir, "fonts.css"), "utf8");
    expect(css).toContain("Generated by dotwear generator. DO NOT EDIT.");
    expect(css).toContain('font-family: "DotGothic16";');
    expect(css).toContain('src: url("./fonts/DotGothic16-Regular.ttf") format("truetype");');
    // 太字を合成させない（にじむため）
    expect(css).toContain("font-weight: 100 900;");
  });
});

describe("emitAndroidFonts", () => {
  it("リソース名は小文字・数字・_ だけにする", () => {
    expect(androidFontResourceName("DotGothic16-Regular.ttf")).toBe("dotgothic16_regular.ttf");
  });

  it("フォントを res/font/ に、ライセンス文を assets/licenses/ に置く", async () => {
    const outDir = await mkdtemp(path.join(os.tmpdir(), "dw-android-fonts-"));
    dirs.push(outDir);
    expect(await emitAndroidFonts({ root: REPO_ROOT, outDir })).toEqual(["dotgothic16_regular.ttf"]);
    expect(await readdir(path.join(outDir, "res", "font"))).toEqual(["dotgothic16_regular.ttf"]);
    expect(await readFile(path.join(outDir, "assets", "licenses", "DotGothic16-OFL.txt"), "utf8")).toContain("SIL Open Font License");
  });
});
