// Flutter（emit/dart.ts）の出力の単体テスト。描いた結果の検証は Dart 側の pixel_roundtrip_test.dart（flutter test）が行う
import { mkdtemp, readFile, rm } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { readdir } from "node:fs/promises";
import { afterEach, describe, expect, it } from "vitest";
import { dartOutDirs, emitDart } from "../src/emit/dart.js";
import { emitDartFonts } from "../src/emit/fonts.js";
import { emitDartTokens } from "../src/emit/tokens.js";
import { dartName } from "../src/emit/naming.js";
import type { IconSource, Palette } from "../src/source/load.js";

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const palette: Palette = { default: { "2": "#2f5bd3" }, "retro-green": { "2": "#0f380f" } };
const ROWS = ["##" + ".".repeat(14), "2" + ".".repeat(15), ...Array(14).fill(".".repeat(16))];
const icon = (name: string, tier: "free" | "pro" = "free"): IconSource => ({ name, category: "test", tier, tags: [], sizes: { "16": ROWS } });

let dir: string | undefined;
afterEach(async () => dir && rm(dir, { recursive: true, force: true }));

async function emit(icons: IconSource[]) {
  dir = await mkdtemp(path.join(os.tmpdir(), "dw-dart-"));
  await emitDart({ icons, palette, packageDir: dir });
  const d = dartOutDirs(dir);
  return {
    icons: await readFile(path.join(d.sources, "dotwear_icons.g.dart"), "utf8"),
    palettes: await readFile(path.join(d.sources, "dotwear_palettes.g.dart"), "utf8"),
    grids: await readFile(path.join(d.tests, "source_grids.g.dart"), "utf8"),
  };
}

describe("dartName", () => {
  it("kebab-case を lowerCamelCase にし、予約語には _ を付ける", () => {
    expect(dartName("arrow-left")).toBe("arrowLeft");
    expect(dartName("default")).toBe("default_");
    expect(dartName("switch")).toBe("switch_");
    expect(dartName("retro-green")).toBe("retroGreen");
  });
});

describe("emitDart", () => {
  it("色ごとの矩形を const の定数として出し、Pro のアイコンは含めない", async () => {
    const out = await emit([icon("arrow-left"), icon("crown", "pro")]);
    expect(out.icons).toContain("// Generated by dotwear generator. DO NOT EDIT.");
    expect(out.icons).toContain("static const arrowLeft = DotwearIconDefinition(");
    expect(out.icons).toContain("DotwearIconLayer(DotwearIconColor.foreground, [0, 0, 2, 1]),");
    expect(out.icons).toContain("DotwearIconLayer(DotwearIconColor.palette(2), [0, 1, 1, 1]),");
    expect(out.icons).toContain("static const all = <DotwearIconDefinition>[arrowLeft];");
    expect(out.icons).not.toContain("crown");
  });

  it("パレットは名前（予約語は _ 付き）と byName で引ける", async () => {
    const out = await emit([icon("save")]);
    expect(out.palettes).toContain("static const default_ = DotwearPalette({2: Color(0xFF2F5BD3)});");
    expect(out.palettes).toContain("static const retroGreen = DotwearPalette({2: Color(0xFF0F380F)});");
    expect(out.palettes).toContain('"retro-green": retroGreen,');
  });

  it("テスト用に元データのマス目を出す", async () => {
    const out = await emit([icon("save")]);
    expect(out.grids).toContain("(DotwearIcons.save, DotwearIconGrid.grid16, [");
    expect(out.grids).toContain(`    ${JSON.stringify(ROWS[0])},`);
  });
});

describe("emitDartTokens・emitDartFonts", () => {
  it("トークンを DotwearTokens の const にし、フォントは書体名.ttf とライセンス文を置く", async () => {
    dir = await mkdtemp(path.join(os.tmpdir(), "dw-dart-tokens-"));
    await emitDartTokens({ root: REPO_ROOT, outDir: path.join(dir, "generated") });
    const dart = await readFile(path.join(dir, "generated", "dotwear_tokens.g.dart"), "utf8");
    expect(dart).toContain("abstract final class DotwearTokens {");
    expect(dart).toMatch(/static const colorOnPrimary = Color\(0xFF[0-9A-F]{6}\);/);
    expect(dart).toMatch(/static const shapePixelUnit = \d+;/);
    expect(dart).toContain('static const typographyFamily = "DotGothic16";');

    await emitDartFonts({ root: REPO_ROOT, outDir: path.join(dir, "fonts") });
    expect((await readdir(path.join(dir, "fonts"))).sort()).toEqual(["DotGothic16-OFL.txt", "DotGothic16.ttf"]);
  });
});
