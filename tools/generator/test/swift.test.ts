// Swift の出力（emit/swift.ts）の単体テスト。
// 描いた結果の検証は Swift 側の PixelRoundtripTests が行うので、ここでは Swift を使わずに確かめられること
// （名前の付け方、矩形が Web と同じであること、衝突や色のないスロットをエラーにすること）を見る
import { mkdtemp, readFile, rm } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { swiftName } from "../src/emit/naming.js";
import { emitSwift, swiftOutDirs } from "../src/emit/swift.js";
import type { IconSource, Palette } from "../src/source/load.js";

const palette: Palette = { default: { "2": "#2F5BD3" }, "retro-green": { "2": "#0f380f" } };

function icon(name: string, rows: string[]): IconSource {
  return { name, category: "test", tier: "free", tags: [], sizes: { "16": rows } };
}
// 16×16 で、左上に # の 2×1、その下に 2 の 1×1
const ROWS = ["##" + ".".repeat(14), "2" + ".".repeat(15), ...Array(14).fill(".".repeat(16))];

let dir: string | undefined;
afterEach(async () => dir && rm(dir, { recursive: true, force: true }));

async function emit(icons: IconSource[]) {
  dir = await mkdtemp(path.join(os.tmpdir(), "dw-swift-"));
  await emitSwift({ icons, palette, packageDir: dir });
  const d = swiftOutDirs(dir);
  return {
    icons: await readFile(path.join(d.sources, "Icons.swift"), "utf8"),
    palette: await readFile(path.join(d.sources, "Palette.swift"), "utf8"),
    grids: await readFile(path.join(d.tests, "SourceGrids.swift"), "utf8"),
  };
}

describe("swiftName", () => {
  it("kebab-case を lowerCamelCase にする", () => {
    expect(swiftName("save")).toBe("save");
    expect(swiftName("arrow-left")).toBe("arrowLeft");
    expect(swiftName("retro-green")).toBe("retroGreen");
  });
  it("予約語はバッククォートで囲む", () => {
    expect(swiftName("default")).toBe("`default`");
    expect(swiftName("repeat")).toBe("`repeat`");
  });
});

describe("emitSwift", () => {
  it("矩形を整数の .init(x, y, w, h) で色ごとに出す", async () => {
    const out = await emit([icon("arrow-left", ROWS)]);
    expect(out.icons.startsWith("// Generated by dotwear generator. DO NOT EDIT.")).toBe(true);
    expect(out.icons).toContain("public static let arrowLeft = DotwearIconDefinition(");
    expect(out.icons).toContain(".init(color: .foreground, rects: [.init(0, 0, 2, 1)])");
    expect(out.icons).toContain(".init(color: .palette(2), rects: [.init(0, 1, 1, 1)])");
    expect(out.icons).toContain("public static let allIcons: [DotwearIconDefinition] = [\n        .arrowLeft,\n    ]");
  });

  it("パレットのテーマを 0xRRGGBB で出す（default は予約語なので囲む）", async () => {
    const out = await emit([icon("save", ROWS)]);
    expect(out.palette).toContain("public static let `default` = DotwearPalette(hex: [2: 0x2f5bd3])");
    expect(out.palette).toContain("public static let retroGreen = DotwearPalette(hex: [2: 0x0f380f])");
  });

  it("テスト用に元データのマス目を出す", async () => {
    const out = await emit([icon("save", ROWS)]);
    expect(out.grids).toContain(`(.save, .grid16, [\n        ${JSON.stringify(ROWS[0])},`);
  });

  it("手書きのメンバーと同じ名前のアイコンはエラーにする", async () => {
    await expect(emit([icon("all-icons", ROWS)])).rejects.toThrow(/all-icons/);
  });

  it("パレットに色のないスロットを使うとエラーにする", async () => {
    const rows = ["9" + ".".repeat(15), ...Array(15).fill(".".repeat(16))];
    await expect(emit([icon("save", rows)])).rejects.toThrow(/スロット 9/);
  });
});
