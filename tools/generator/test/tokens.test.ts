import { mkdtemp, readFile, rm } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { emitSwiftTokens, emitTokens, WEB_TOKEN_FILES } from "../src/emit/tokens.js";

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");

interface DtcgToken {
  $type: string;
  $value: unknown;
}

// 元データの DTCG トークンを [パス, トークン] の一覧にする
async function sourceTokens(): Promise<[string[], DtcgToken][]> {
  const out: [string[], DtcgToken][] = [];
  const walk = (node: Record<string, unknown>, p: string[]) => {
    if ("$value" in node) {
      out.push([p, node as unknown as DtcgToken]);
      return;
    }
    for (const [k, v] of Object.entries(node)) if (!k.startsWith("$")) walk(v as Record<string, unknown>, [...p, k]);
  };
  for (const f of WEB_TOKEN_FILES) walk(JSON.parse(await readFile(path.join(REPO_ROOT, "tokens", f), "utf8")), []);
  return out;
}

// 元データの値を、CSS に出るはずの文字列にする
function expectedCss(t: DtcgToken): string {
  switch (t.$type) {
    case "dimension": {
      const v = t.$value as { value: number; unit: string };
      return `${v.value}${v.unit}`;
    }
    case "fontFamily":
      return (t.$value as string[]).join(", ");
    default:
      return String(t.$value);
  }
}

let outDir: string;
let css: string;
let ts: string;

beforeAll(async () => {
  outDir = await mkdtemp(path.join(os.tmpdir(), "dotwear-tokens-"));
  await emitTokens({ root: REPO_ROOT, outDir });
  css = await readFile(path.join(outDir, "tokens.css"), "utf8");
  ts = await readFile(path.join(outDir, "tokens.ts"), "utf8");
});

afterAll(async () => {
  await rm(outDir, { recursive: true, force: true });
});

describe("emitTokens", () => {
  it("すべてのトークンを --dw-* の CSS 変数として、元データと同じ値で出す", async () => {
    const tokens = await sourceTokens();
    expect(tokens.length).toBeGreaterThan(0);
    for (const [p, t] of tokens) {
      expect(css).toContain(`--dw-${p.join("-")}: ${expectedCss(t)};`);
    }
  });

  it("pixel-unit は整数の px（整数倍の表示を保つため）", () => {
    expect(css).toMatch(/--dw-shape-pixel-unit: [1-9]\d*px;/);
  });

  it("ドット数のトークンは単位なしで出す", () => {
    expect(css).toMatch(/--dw-shape-border-width: \d+;/);
  });

  it("TS では値と CSS 変数の参照を、キーを camelCase にして出す", () => {
    expect(ts).toContain('"onPrimary": "#f8f8f8"');
    expect(ts).toContain('"onPrimary": "var(--dw-color-on-primary)"');
    expect(ts).toContain('"borderWidth": 1');
  });

  it("生成物のヘッダーを入れる", () => {
    expect(css).toContain("Generated by dotwear generator. DO NOT EDIT.");
    expect(ts.startsWith("// Generated by dotwear generator. DO NOT EDIT.")).toBe(true);
  });

  it("パレットは含めない（アイコンのパッケージに入れる。ADR-009）", () => {
    expect(css).not.toContain("palette");
  });
});

describe("emitSwiftTokens", () => {
  let swiftDir: string;
  let swift: string;
  beforeAll(async () => {
    swiftDir = await mkdtemp(path.join(os.tmpdir(), "dotwear-swift-tokens-"));
    await emitSwiftTokens({ root: REPO_ROOT, outDir: swiftDir });
    swift = await readFile(path.join(swiftDir, "DotwearTokens.swift"), "utf8");
  });
  afterAll(async () => rm(swiftDir, { recursive: true, force: true }));

  it("すべてのトークンを DotwearTokens.<グループ>.<名前> として出す", async () => {
    for (const [p] of await sourceTokens()) {
      const name = p.slice(1).join("-").replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
      expect(swift).toMatch(new RegExp(`public static let ${name}\\b`));
    }
  });

  it("色は sRGB の SwiftUI.Color、ドット数は Int、長さは CGFloat", () => {
    expect(swift).toContain(
      "public static let onPrimary = SwiftUI.Color(.sRGB, red: 0xf8 / 255.0, green: 0xf8 / 255.0, blue: 0xf8 / 255.0, opacity: 1)",
    );
    expect(swift).toContain("public static let borderWidth: Int = 1");
    expect(swift).toMatch(/public static let pixelUnit: CGFloat = [1-9]\d*\n/);
  });

  it("生成物のヘッダーを入れ、パレットは含めない", () => {
    expect(swift.startsWith("// Generated by dotwear generator. DO NOT EDIT.")).toBe(true);
    expect(swift).not.toContain("palette");
  });
});
