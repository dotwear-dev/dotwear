// Android の出力（emit/android.ts と Kotlin のトークン）の単体テスト。
// 描いた結果の検証は Kotlin 側の PixelRoundtripTest（Robolectric）が行う
import { mkdtemp, readFile, rm } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { afterEach, describe, expect, it } from "vitest";
import { androidOutDirs, emitAndroid } from "../src/emit/android.js";
import { kotlinName } from "../src/emit/naming.js";
import { emitKotlinTokens } from "../src/emit/tokens.js";
import type { IconSource, Palette } from "../src/source/load.js";

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
const palette: Palette = { default: { "2": "#2f5bd3" }, "retro-green": { "2": "#0f380f" } };
const ROWS = ["##" + ".".repeat(14), "2" + ".".repeat(15), ...Array(14).fill(".".repeat(16))];
const icon = (name: string, rows = ROWS): IconSource => ({ name, category: "test", tier: "free", tags: [], sizes: { "16": rows } });

let dir: string | undefined;
afterEach(async () => dir && rm(dir, { recursive: true, force: true }));

async function emit(icons: IconSource[]) {
  dir = await mkdtemp(path.join(os.tmpdir(), "dw-android-"));
  await emitAndroid({ icons, palette, projectDir: dir });
  const d = androidOutDirs(dir);
  return {
    icons: await readFile(path.join(d.sources, "DotwearIcons.kt"), "utf8"),
    palette: await readFile(path.join(d.sources, "DotwearPaletteThemes.kt"), "utf8"),
    grids: await readFile(path.join(d.tests, "SourceGrids.kt"), "utf8"),
  };
}

describe("kotlinName", () => {
  it("kebab-case を PascalCase にする", () => {
    expect(kotlinName("save")).toBe("Save");
    expect(kotlinName("arrow-left")).toBe("ArrowLeft");
  });
});

describe("emitAndroid", () => {
  it("矩形を [x, y, 幅, 高さ] の IntArray で色ごとに出す", async () => {
    const out = await emit([icon("arrow-left")]);
    expect(out.icons.startsWith("// Generated by dotwear generator. DO NOT EDIT.\npackage dev.dotwear.icons")).toBe(true);
    expect(out.icons).toContain("val ArrowLeft: DotwearIconDefinition by lazy {");
    expect(out.icons).toContain("DotwearIconLayer(DotwearIconColor.Foreground, intArrayOf(0, 0, 2, 1))");
    expect(out.icons).toContain("DotwearIconLayer(DotwearIconColor.Palette(2), intArrayOf(0, 1, 1, 1))");
    expect(out.icons).toContain("listOf(ArrowLeft)");
  });

  it("パレットのテーマを DotwearPalette.Companion の拡張プロパティで出す", async () => {
    const out = await emit([icon("save")]);
    expect(out.palette).toContain("val DotwearPalette.Companion.Default: DotwearPalette get() = paletteDefault");
    expect(out.palette).toContain("DotwearPalette.fromHex(2 to 0x0F380FL)");
  });

  it("テスト用に元データのマス目を出す", async () => {
    const out = await emit([icon("save")]);
    expect(out.grids).toContain(`Triple(DotwearIcons.Save, DotwearIconGrid.Grid16, listOf(\n        ${JSON.stringify(ROWS[0])},`);
  });

  it("パレットに色のないスロットを使うとエラーにする", async () => {
    await expect(emit([icon("save", ["9" + ".".repeat(15), ...Array(15).fill(".".repeat(16))])])).rejects.toThrow(/スロット 9/);
  });
});

describe("emitKotlinTokens", () => {
  it("トークンを DotwearTokens.<Group>.<Name> として Compose の型で出す", async () => {
    dir = await mkdtemp(path.join(os.tmpdir(), "dw-kotlin-tokens-"));
    await emitKotlinTokens({ root: REPO_ROOT, outDir: dir });
    const kt = await readFile(path.join(dir, "DotwearTokens.kt"), "utf8");
    expect(kt).toContain("package dev.dotwear.compose");
    expect(kt).toContain("val OnPrimary = androidx.compose.ui.graphics.Color(0xFFF8F8F8)");
    expect(kt).toMatch(/val PixelUnit: Int = [1-9]\d*\n/);
    expect(kt).toContain("val BorderWidth: Int = 1");
    expect(kt).not.toContain("palette");
  });
});
